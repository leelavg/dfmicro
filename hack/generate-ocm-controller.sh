#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
overlay_dir="${script_dir}/ocm-controller"
overlay_file="${overlay_dir}/kustomization.yaml"
assets_dir="${script_dir}/../internal/addon/ocm/assets"
manifest_file="${assets_dir}/ocm-controller.yaml"
marker="${assets_dir}/.ocm-controller-kustomization"
overlay_state="$(cksum <"${overlay_file}")"

if [[ -f "${marker}" ]] && [[ "$(<"${marker}")" == "${overlay_state}" ]] && [[ -s "${manifest_file}" ]]; then
	echo "OCM controller manifest is up to date"
	exit 0
fi

missing=()
for dependency in kustomize; do
	if ! command -v "${dependency}" >/dev/null 2>&1; then
		missing+=("${dependency}")
	fi
done
if ((${#missing[@]} > 0)); then
	echo "error: missing required tools: ${missing[*]}" >&2
	exit 1
fi

tmp_dir="$(mktemp -d)"
trap 'rm -rf "${tmp_dir}"' EXIT
kustomize build "${overlay_dir}" >"${tmp_dir}/rendered.yaml"
if ! grep -q 'imagePullPolicy: IfNotPresent' "${tmp_dir}/rendered.yaml"; then
	echo "error: rendered OCM controller has no IfNotPresent image pull policy" >&2
	exit 1
fi

mkdir -p "${assets_dir}"
{
	echo "# Generated by hack/generate-ocm-controller.sh. DO NOT EDIT."
	cat "${tmp_dir}/rendered.yaml"
} >"${tmp_dir}/ocm-controller.yaml"
mv "${tmp_dir}/ocm-controller.yaml" "${manifest_file}"
printf '%s\n' "${overlay_state}" >"${marker}"
echo "Generated OCM controller manifest in ${manifest_file}"
