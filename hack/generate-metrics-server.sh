#!/usr/bin/env bash
set -euo pipefail

# Generated manifests are checked in. Curl and yq are only needed when the version changes.

version="${METRICS_SERVER_VERSION:?METRICS_SERVER_VERSION is required}"
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
addon_dir="${script_dir}/../internal/addon/metrics"
assets_dir="${addon_dir}/assets"
manifest="${assets_dir}/components.yaml"
version_file="${addon_dir}/version_gen.go"
marker="${assets_dir}/.metrics-server-version"
state="metrics-server=v${version} kubelet-ca=kube-system/kubelet-client-ca"

if [[ -f "${marker}" && "$(<"${marker}")" == "${state}" && -s "${manifest}" && -s "${version_file}" ]]; then
	echo "Metrics Server v${version} manifest is up to date"
	exit 0
fi

missing=()
for dependency in curl gofmt grep yq; do
	if ! command -v "${dependency}" >/dev/null 2>&1; then
		missing+=("${dependency}")
	fi
done
if ((${#missing[@]} > 0)); then
	echo "error: missing required tools: ${missing[*]}" >&2
	exit 1
fi

tmp_dir="$(mktemp -d)"
trap 'rm -rf "${tmp_dir}"' EXIT
curl -fsSL --retry 5 --max-filesize 10000 \
	"https://github.com/kubernetes-sigs/metrics-server/releases/download/v${version}/components.yaml" \
	-o "${tmp_dir}/components.yaml"
if ! grep -Fq "image: registry.k8s.io/metrics-server/metrics-server:v${version}" "${tmp_dir}/components.yaml"; then
	echo "error: Metrics Server manifest does not contain version v${version}" >&2
	exit 1
fi

yq -i '
	select(.kind == "Deployment" and .metadata.name == "metrics-server") |= (
		.spec.template.spec.volumes += [{"name": "ca-bundle", "configMap": {"name": "kubelet-client-ca"}}] |
		.spec.template.spec.containers[0].volumeMounts += [{"name": "ca-bundle", "mountPath": "/var/run/secrets/kubernetes.io/certs/ca.crt", "subPath": "ca.crt", "readOnly": true}] |
		.spec.template.spec.containers[0].args += ["--kubelet-certificate-authority=/var/run/secrets/kubernetes.io/certs/ca.crt"] |
		.spec.template.spec.containers[0].resources.requests = {"cpu": "50m", "memory": "64Mi"}
	)
' "${tmp_dir}/components.yaml"
yq -i '
	(.metadata.labels = (.metadata.labels // {})) |
	.metadata.labels."app.kubernetes.io/created-by" = "dfmicro"
' "${tmp_dir}/components.yaml"
yq -i '
	select(.kind == "Deployment" and .metadata.name == "metrics-server") |= (
		.spec.template.metadata.labels."app.kubernetes.io/created-by" = "dfmicro"
	)
' "${tmp_dir}/components.yaml"

mkdir -p "${assets_dir}"
mv "${tmp_dir}/components.yaml" "${manifest}"
cat >"${version_file}" <<EOF
package metrics

// Code generated by hack/generate-metrics-server.sh. DO NOT EDIT.
const metricsVersion = "v${version}"
EOF
gofmt -w "${version_file}"
printf '%s\n' "${state}" >"${marker}"
echo "Generated Metrics Server v${version} manifest in ${manifest}"
