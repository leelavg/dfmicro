#!/usr/bin/env bash
set -euo pipefail

# Requires curl, helm, tar, and yq. The generated manifest is checked in so
# these tools are only needed when the chart version or source commit changes.

version="${VOLSYNC_VERSION:?VOLSYNC_VERSION is required}"
commit="${VOLSYNC_CHART_COMMIT:?VOLSYNC_CHART_COMMIT is required}"
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
assets_dir="${script_dir}/../internal/addon/odr/assets"
manifest_file="${assets_dir}/volsync.yaml"
marker="${assets_dir}/.volsync-version"
state="${version} ${commit} namespace=volsync-system"

if [[ -f "${marker}" ]] && [[ "$(<"${marker}")" == "${state}" ]] && [[ -s "${manifest_file}" ]]; then
	echo "VolSync ${version} manifests are up to date"
	exit 0
fi

missing=()
for dependency in curl helm tar yq; do
	if ! command -v "${dependency}" >/dev/null 2>&1; then
		missing+=("${dependency}")
	fi
done
if ((${#missing[@]} > 0)); then
	echo "error: missing required tools: ${missing[*]}" >&2
	exit 1
fi

tmp_dir="$(mktemp -d)"
trap 'rm -rf "${tmp_dir}"' EXIT
archive="${tmp_dir}/volsync-addon-controller.tar.gz"
chart_dir="${tmp_dir}/source/helmcharts/stable-0.17/volsync"
rendered="${tmp_dir}/volsync.yaml"

curl -fsSL --retry 5 "https://github.com/stolostron/volsync-addon-controller/archive/${commit}.tar.gz" -o "${archive}"
mkdir -p "${tmp_dir}/source"
tar -xzf "${archive}" --strip-components=1 -C "${tmp_dir}/source"

chart_version="$(yq -r '.version' "${chart_dir}/Chart.yaml")"
if [[ "${chart_version}" != "${version}" ]]; then
	echo "error: expected VolSync chart ${version}, found ${chart_version} at ${commit}" >&2
	exit 1
fi

cat >"${rendered}" <<'EOF'
# Generated by hack/generate-volsync.sh. DO NOT EDIT.
---
apiVersion: v1
kind: Namespace
metadata:
  name: volsync-system
  labels:
    app.kubernetes.io/created-by: dfmicro
EOF
helm template volsync "${chart_dir}" \
	--namespace volsync-system \
	--api-versions security.openshift.io/v1/SecurityContextConstraints \
	--set manageCRDs=true \
	>>"${rendered}"
yq -i 'select(.kind == "Deployment" or .kind == "Role" or .kind == "RoleBinding" or .kind == "Service" or .kind == "ServiceAccount") |= (.metadata.namespace = "volsync-system")' "${rendered}"

mkdir -p "${assets_dir}"
mv "${rendered}" "${manifest_file}"
printf '%s\n' "${state}" >"${marker}"
echo "Generated VolSync ${version} manifests in ${manifest_file}"
