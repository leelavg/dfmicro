#!/usr/bin/env bash
set -euo pipefail

# The generated manifest is checked in. Curl is only needed when its version changes.

version="${ARGOCD_VERSION:?ARGOCD_VERSION is required}"
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
assets_dir="${script_dir}/../internal/addon/ocm/assets/argocd"
manifest="${assets_dir}/install.yaml"
marker="${assets_dir}/.argocd-version"
version_file="${script_dir}/../internal/addon/ocm/argocd_gen.go"

if [[ -f "${marker}" && "$(<"${marker}")" == "${version}" && -s "${manifest}" && -s "${version_file}" ]]; then
	echo "Argo CD ${version} manifest is up to date"
	exit 0
fi

if ! command -v curl >/dev/null 2>&1; then
	echo "error: missing required tool: curl" >&2
	exit 1
fi

tmp_dir="$(mktemp -d)"
trap 'rm -rf "${tmp_dir}"' EXIT
curl -fsSL --retry 5 --max-filesize 5000000 \
	"https://raw.githubusercontent.com/argoproj/argo-cd/v${version}/manifests/install.yaml" \
	-o "${tmp_dir}/install.yaml"
if ! grep -Fq "image: quay.io/argoproj/argocd:v${version}" "${tmp_dir}/install.yaml"; then
	echo "error: Argo CD manifest does not contain version ${version}" >&2
	exit 1
fi

mkdir -p "${assets_dir}"
mv "${tmp_dir}/install.yaml" "${manifest}"
printf '%s\n' "${version}" >"${marker}"
cat >"${version_file}" <<EOF
package ocm

// Code generated by hack/generate-argocd.sh. DO NOT EDIT.
const argocdVersion = "${version}"
EOF
echo "Generated Argo CD ${version} manifest in ${manifest}"
